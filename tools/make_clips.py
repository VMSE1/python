def fmt(cap, v):
    def rep(m):
        x = v.get(m.group(1))
        if x is None:
            return m.group(0)
        return x[1:-1] if x[:1] in "'\"" else x
    return re.sub(r"\{(\w+)\}", rep, cap)


def build_trace(c):
    steps = trace(c["code"], c["inputs"])
    seen, out = {}, []
    for i, s0 in enumerate(steps):
        # показываем состояние ПОСЛЕ строки: это то, что строка сделала
        s = dict(steps[i + 1]) if i + 1 < len(steps) else dict(s0)
        s["l"] = s0["l"]
        l = s["l"]
        if l < 0:
            out.append({"l": -1, "v": s["v"], "o": s["o"], "c": c["outro"], "d": 5.0})
            continue
        k = seen.get(l, 0)
        seen[l] = k + 1
        caps = c["caps"].get(l)
        if not caps:
            raise SystemExit(f"{c['id']}: нет подписи для строки {l}")
        cap = fmt(caps[min(k, len(caps) - 1)], s["v"])
        out.append({"l": l, "v": s["v"], "o": s["o"], "f": s.get("f", ""), "c": cap, "d": 5.5 if k == 0 else 3.6})
    return {"id": c["id"], "type": "trace", "l": c["l"], "title": c["title"], "file": c["file"],
            "code": c["code"], "intro": c["intro"], "steps": out}


def main():
    clips = []
    for c in TASK_CLIPS:
        clips.append({"id": c["id"], "type": "task", "task": c["task"], "full": c["full"], "title": c["title"],
                      "sub": c["sub"], "keep": c["keep"], "typed": c["typed"], "caps": c["caps"]})
    for c in THEORY_CLIPS:
        clips.append(build_trace(c))
    here = os.path.dirname(os.path.abspath(__file__))
    dst = os.path.join(here, "..", "docs", "data", "clips.js")
    with open(dst, "w", encoding="utf-8", newline="\n") as f:
        f.write("/* Сгенерировано tools/make_clips.py. Не править руками. */\nwindow.CLIPS = " + json.dumps(clips, ensure_ascii=False) + ";\n")
    for c in clips:
        if c["type"] == "trace":
            sec = 3 + sum(s["d"] for s in c["steps"])
            print(c["id"], len(c["steps"]), "шагов, ~%d с" % sec)
    print("роликов:", len(clips))


if __name__ == "__main__":
    main()
